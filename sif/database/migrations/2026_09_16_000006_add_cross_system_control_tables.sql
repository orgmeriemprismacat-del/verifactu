CREATE TABLE IF NOT EXISTS edition_lifecycle_event (
    UUID_EDITION_EVENT CHAR(36) NOT NULL PRIMARY KEY,
    PRODUCT_TYPE VARCHAR(40) NOT NULL,
    PRODUCT_CODE VARCHAR(80) NOT NULL,
    PRODUCT_EDITION VARCHAR(80) NOT NULL,
    ACTION VARCHAR(30) NOT NULL,
    RESULT VARCHAR(30) NOT NULL,
    STATUS_BEFORE VARCHAR(30) NULL,
    STATUS_AFTER VARCHAR(30) NOT NULL,
    EFFECTIVE_AT DATETIME NOT NULL,
    REASON_CODE VARCHAR(80) NOT NULL,
    AFFECTED_OPERATION_COUNT INT NOT NULL DEFAULT 0,
    AFFECTED_RESERVATION_COUNT INT NOT NULL DEFAULT 0,
    ACTOR_ID VARCHAR(100) NOT NULL,
    CORRELATION_ID VARCHAR(100) NOT NULL,
    SNAPSHOT_BEFORE_HASH CHAR(64) NULL,
    SNAPSHOT_AFTER_HASH CHAR(64) NOT NULL,
    METADATA_JSON JSON NULL,
    OCCURRED_AT DATETIME NOT NULL,
    RECORDED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_edition_lifecycle_edition (PRODUCT_TYPE, PRODUCT_CODE, PRODUCT_EDITION, OCCURRED_AT),
    KEY idx_edition_lifecycle_correlation (CORRELATION_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS edition_operation_impact (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    UUID_EDITION_EVENT CHAR(36) NOT NULL,
    UUID_OPERATION CHAR(36) NOT NULL,
    UUID_CAPACITY_RESERVATION CHAR(36) NULL,
    IMPACT_TYPE VARCHAR(40) NOT NULL,
    REQUIRED_ACTION VARCHAR(40) NOT NULL,
    ECONOMIC_DECISION VARCHAR(40) NULL,
    FISCAL_DECISION VARCHAR(40) NULL,
    STATUS VARCHAR(30) NOT NULL,
    RESULT_JSON JSON NULL,
    RESOLVED_BY VARCHAR(100) NULL,
    RESOLVED_AT DATETIME NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_edition_operation_impact (UUID_EDITION_EVENT, UUID_OPERATION),
    KEY idx_edition_operation_status (STATUS, REQUIRED_ACTION),
    CONSTRAINT fk_edition_impact_event
        FOREIGN KEY (UUID_EDITION_EVENT) REFERENCES edition_lifecycle_event(UUID_EDITION_EVENT),
    CONSTRAINT fk_edition_impact_operation
        FOREIGN KEY (UUID_OPERATION) REFERENCES commercial_operation(UUID_OPERATION),
    CONSTRAINT fk_edition_impact_reservation
        FOREIGN KEY (UUID_CAPACITY_RESERVATION) REFERENCES capacity_reservation(UUID_CAPACITY_RESERVATION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS address_validation_case (
