-- Additive controls found in the third executable-surface audit.
-- These records keep consent, identity, edition, address and Moodle/Prisma
-- reconciliation separate from invoices and payment transactions.

CREATE TABLE IF NOT EXISTS communication_consent (
    UUID_CONSENT CHAR(36) NOT NULL PRIMARY KEY,
    SUBJECT_KEY VARCHAR(100) NOT NULL,
    PURPOSE_CODE VARCHAR(60) NOT NULL,
    CHANNEL VARCHAR(30) NOT NULL,
    SCOPE_CODE VARCHAR(60) NOT NULL,
    NOTICE_VERSION VARCHAR(40) NOT NULL,
    LAWFUL_BASIS VARCHAR(40) NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    SOURCE_SYSTEM VARCHAR(40) NOT NULL,
    SOURCE_REFERENCE VARCHAR(120) NULL,
    CAPTURED_AT DATETIME NOT NULL,
    WITHDRAWN_AT DATETIME NULL,
    EXPIRES_AT DATETIME NULL,
    CURRENT_EVENT_UUID CHAR(36) NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_communication_consent_scope (SUBJECT_KEY, PURPOSE_CODE, CHANNEL, SCOPE_CODE),
    KEY idx_communication_consent_status (STATUS, PURPOSE_CODE, CHANNEL),
    KEY idx_communication_consent_subject (SUBJECT_KEY, CAPTURED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS communication_consent_event (
    UUID_EVENT CHAR(36) NOT NULL PRIMARY KEY,
    UUID_CONSENT CHAR(36) NOT NULL,
    ACTION VARCHAR(30) NOT NULL,
    RESULT VARCHAR(30) NOT NULL,
    FROM_STATUS VARCHAR(30) NULL,
    TO_STATUS VARCHAR(30) NOT NULL,
    NOTICE_VERSION VARCHAR(40) NOT NULL,
    EVIDENCE_HASH CHAR(64) NOT NULL,
    ACTOR_TYPE VARCHAR(20) NOT NULL,
    ACTOR_ID VARCHAR(100) NULL,
    SOURCE_SYSTEM VARCHAR(40) NOT NULL,
    SOURCE_REFERENCE VARCHAR(120) NULL,
    CORRELATION_ID VARCHAR(100) NOT NULL,
    REASON_CODE VARCHAR(80) NULL,
    METADATA_JSON JSON NULL,
    OCCURRED_AT DATETIME NOT NULL,
    RECORDED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_consent_event_timeline (UUID_CONSENT, OCCURRED_AT),
    KEY idx_consent_event_correlation (CORRELATION_ID),
    CONSTRAINT fk_consent_event_consent
        FOREIGN KEY (UUID_CONSENT) REFERENCES communication_consent(UUID_CONSENT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE communication_consent
    ADD CONSTRAINT fk_communication_consent_current_event
        FOREIGN KEY (CURRENT_EVENT_UUID) REFERENCES communication_consent_event(UUID_EVENT);

CREATE TABLE IF NOT EXISTS external_identity_link (
