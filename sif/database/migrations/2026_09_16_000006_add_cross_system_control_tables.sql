    KEY idx_academic_reconciliation_status (UUID_RUN, RESOLUTION_STATUS),
    KEY idx_academic_reconciliation_enrollment (ENROLLMENT_KEY, EXTERNAL_SYSTEM),
    CONSTRAINT fk_academic_reconciliation_run
        FOREIGN KEY (UUID_RUN) REFERENCES reconciliation_run(UUID_RUN),
    CONSTRAINT fk_academic_reconciliation_operation
        FOREIGN KEY (UUID_OPERATION) REFERENCES commercial_operation(UUID_OPERATION)
