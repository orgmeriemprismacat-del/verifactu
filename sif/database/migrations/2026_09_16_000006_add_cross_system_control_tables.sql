    ENROLLMENT_KEY VARCHAR(100) NULL,
    SUBJECT_KEY VARCHAR(100) NULL,
    UUID_OPERATION CHAR(36) NULL,
    PRODUCT_EDITION VARCHAR(80) NULL,
    EXTERNAL_SYSTEM VARCHAR(40) NOT NULL,
    EXTERNAL_REFERENCE VARCHAR(120) NULL,
    DIFFERENCE_TYPE VARCHAR(50) NOT NULL,
    SOURCE_SNAPSHOT_HASH CHAR(64) NOT NULL,
    TARGET_SNAPSHOT_HASH CHAR(64) NOT NULL,
    DIFFERENCE_JSON JSON NOT NULL,
    RESOLUTION_STATUS VARCHAR(30) NOT NULL,
    RESOLUTION_ACTION VARCHAR(50) NULL,
