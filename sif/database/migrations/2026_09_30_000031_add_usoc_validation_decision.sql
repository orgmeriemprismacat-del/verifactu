CREATE TABLE IF NOT EXISTS usoc_validation_decision (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    UUID_DECISION CHAR(36) NOT NULL UNIQUE,
    REQUEST_ID VARCHAR(120) NOT NULL UNIQUE,
    CORRELATION_ID VARCHAR(120) NOT NULL,
    ID_INSC BIGINT NOT NULL,
    DESIRED_VALID_DESC TINYINT NOT NULL,
    STATE VARCHAR(30) NOT NULL,
    ACTOR_ID VARCHAR(120) NOT NULL,
    ACTOR_ROLES VARCHAR(255) NULL,
    LEGACY_BEFORE_VALID_DESC TINYINT NOT NULL,
    LEGACY_AFTER_VALID_DESC TINYINT NULL,
    LEGACY_STATE_HASH CHAR(64) NULL,
    REQUESTED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    COMMITTED_AT DATETIME(6) NULL,
    LAST_RECONCILED_AT DATETIME(6) NULL,
    REVIEW_REASON VARCHAR(255) NULL,
    KEY idx_usoc_validation_inscription (ID_INSC, REQUESTED_AT),
    KEY idx_usoc_validation_state (STATE, REQUESTED_AT),
    CONSTRAINT chk_usoc_validation_desired CHECK (DESIRED_VALID_DESC IN (1, 2)),
    CONSTRAINT chk_usoc_validation_state CHECK (STATE IN ('REQUESTED', 'COMMITTED', 'REVIEW_REQUIRED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
